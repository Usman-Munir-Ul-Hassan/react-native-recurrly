import React from "react";
import { Alert, Linking, Pressable, ScrollView, Share, Text, View } from "react-native";
import { SafeAreaView } from "react-native-safe-area-context";
import { useLocalSearchParams, useRouter } from "expo-router";
import { Colors, Radius } from "@/constants/theme";
import { useSubscriptions } from "@/context/subscription-context";
import { useUserProfile } from "@/hooks/use-user-profile";
import { AppButton } from "@/components/ui/app-button";
import { ImageWithSkeleton } from "@/components/ui/image-with-skeleton";
import { UserAvatar } from "@/components/ui/user-avatar";

export default function SubscriptionDetailScreen() {
  const { id } = useLocalSearchParams<{ id: string }>();
  const router = useRouter();
  const { photoUrl, initials: userInitials } = useUserProfile();
  const {
    getSubscription,
    cancelSubscription,
    pauseSubscription,
    resumeSubscription,
    deleteSubscription,
  } = useSubscriptions();

  const subscription = getSubscription(id);

  if (!subscription) {
    return (
      <SafeAreaView className="flex-1 bg-white items-center justify-center p-6">
        <Text style={{ fontSize: 16, color: Colors.pitchBlack, marginBottom: 16 }}>
          Subscription not found
        </Text>
        <AppButton title="← Back to Subscriptions" onPress={() => router.back()} />
      </SafeAreaView>
    );
  }

  const isCancelled = subscription.status === "Cancelled";
  const isPaused = subscription.status === "Paused";

  const handleCancel = () => {
    Alert.alert(
      "Cancel Subscription",
      `Are you sure you want to cancel your ${subscription.name} subscription?`,
      [
        { text: "Keep Subscription", style: "cancel" },
        {
          text: "Yes, Cancel",
          style: "destructive",
          onPress: () => {
            cancelSubscription(subscription.id);
            Alert.alert("Subscription Cancelled", `${subscription.name} has been cancelled.`);
          },
        },
      ]
    );
  };

  const handleTogglePause = () => {
    if (isPaused) {
      resumeSubscription(subscription.id);
      Alert.alert("Subscription Resumed", `${subscription.name} is now active.`);
    } else {
      Alert.alert(
        "Pause Subscription",
        `Do you want to pause your ${subscription.name} subscription? You can resume it anytime.`,
        [
          { text: "Cancel", style: "cancel" },
          {
            text: "Pause",
            onPress: () => {
              pauseSubscription(subscription.id);
              Alert.alert("Subscription Paused", `${subscription.name} has been paused.`);
            },
          },
        ]
      );
    }
  };

  const handleDelete = () => {
    Alert.alert(
      "Delete Subscription",
      `Are you sure you want to permanently remove ${subscription.name} from your chronicle?`,
      [
        { text: "Cancel", style: "cancel" },
        {
          text: "Delete",
          style: "destructive",
          onPress: () => {
            deleteSubscription(subscription.id);
            router.back();
          },
        },
      ]
    );
  };

  const handleManage = async () => {
    const serviceUrls: Record<string, string> = {
      chatgpt: "https://chatgpt.com",
      openai: "https://chatgpt.com",
      spotify: "https://www.spotify.com/account/overview",
      netflix: "https://www.netflix.com/youraccount",
      github: "https://github.com/settings/billing",
      claude: "https://claude.ai/settings/billing",
      figma: "https://www.figma.com/settings",
      dropbox: "https://www.dropbox.com/account/plan",
      notion: "https://www.notion.so/profile",
      linear: "https://linear.app/settings/billing",
    };

    const key = Object.keys(serviceUrls).find((k) =>
      subscription.name.toLowerCase().includes(k)
    );
    const targetUrl = key
      ? serviceUrls[key]
      : `https://www.google.com/search?q=${encodeURIComponent(subscription.name + " manage subscription")}`;

    const supported = await Linking.canOpenURL(targetUrl);
    if (supported) {
      await Linking.openURL(targetUrl);
    } else {
      Alert.alert("Manage Portal", `Opening ${subscription.name} portal: ${targetUrl}`);
    }
  };

  const handleShareReceipt = async () => {
    const receiptText = [
      `===============================`,
      `       CHRONICLE RECEIPT       `,
      `===============================`,
      `Service:        ${subscription.name}`,
      `Category:       ${subscription.category}`,
      `Status:         ${subscription.status}`,
      `Monthly Amount: ${subscription.price}`,
      `Billing Cycle:  ${subscription.billingCycle}`,
      `Next Renewal:   ${subscription.nextRenewalFull}`,
      `Payment Method: ${subscription.paymentMethod}`,
      `Billed To:      ${subscription.invoiceEmail}`,
      `Receipt Ref:    ${subscription.id.toUpperCase()}`,
      `===============================`,
      `Generated by Chronicle App`,
    ].join("\n");

    try {
      await Share.share({
        title: `${subscription.name} - Receipt`,
        message: receiptText,
      });
    } catch {
      // Ignored if user dismissed
    }
  };

  const detailsRows = [
    { label: "Billing cycle", value: subscription.billingCycle },
    { label: "Next renewal", value: subscription.nextRenewalFull },
    { label: "Payment method", value: subscription.paymentMethod },
    { label: "Category", value: subscription.category },
    { label: "Invoice email", value: subscription.invoiceEmail },
  ];

  return (
    <SafeAreaView edges={["top"]} className="flex-1 bg-white">
      {/* Top Header Bar */}
      <View className="flex-row items-center justify-between px-5 py-3 border-b border-[#E2E2E2]">
        <Pressable
          onPress={() => router.back()}
          hitSlop={12}
          className="flex-row items-center py-1"
        >
          <Text style={{ fontSize: 18, color: Colors.pitchBlack, marginRight: 6 }}>
            ←
          </Text>
          <Text style={{ fontSize: 13, fontWeight: "500", color: Colors.pitchBlack }}>
            Subscriptions
          </Text>
        </Pressable>

        {/* Real User Profile Avatar */}
        <UserAvatar photoUrl={photoUrl} initials={userInitials} size={30} />
      </View>

      <ScrollView
        showsVerticalScrollIndicator={false}
        contentContainerStyle={{ paddingHorizontal: 20, paddingTop: 20, paddingBottom: 40 }}
      >
        {/* Brand Logo / Monogram Box & Titles */}
        <View className="flex-row items-center mb-6">
          <View
            className="items-center justify-center mr-4"
            style={{
              width: 52,
              height: 52,
              backgroundColor: Colors.limestone,
              borderRadius: Radius.tag,
              borderWidth: 1,
              borderColor: Colors.fog,
              overflow: "hidden",
            }}
          >
            <ImageWithSkeleton
              uri={subscription.logoUrl}
              fallbackText={subscription.initials}
              width={34}
              height={34}
              borderRadius={Radius.tag}
              fallbackTextColor={Colors.pitchBlack}
              fallbackTextSize={18}
            />
          </View>

          <View className="flex-1">
            <Text
              style={{
                fontSize: 20,
                fontWeight: "700",
                color: Colors.pitchBlack,
                letterSpacing: -0.5,
                marginBottom: 2,
              }}
            >
              {subscription.name}
            </Text>
            <Text
              style={{
                fontSize: 13,
                color: Colors.graphite,
              }}
            >
              {subscription.price} • {subscription.cadence}
            </Text>
          </View>
        </View>

        {/* Status & Billing Tag Row */}
        <View className="flex-row items-center mb-6">
          <View
            className="px-2.5 py-1 mr-3"
            style={{
              backgroundColor: isCancelled
                ? "#FEE2E2"
                : isPaused
                ? "#FEF3C7"
                : Colors.limestone,
              borderRadius: Radius.tag,
            }}
          >
            <Text
              style={{
                fontSize: 12,
                fontWeight: "600",
                color: isCancelled
                  ? "#991B1B"
                  : isPaused
                  ? "#92400E"
                  : Colors.pitchBlack,
              }}
            >
              {subscription.status}
            </Text>
          </View>
          <Text style={{ fontSize: 13, color: Colors.graphite }}>
            {isCancelled
              ? "Subscription discontinued"
              : isPaused
              ? "Subscription paused"
              : `Renews ${subscription.renewalDateShort}`}
          </Text>
        </View>

        {/* Subscription Details Table Card */}
        <View
          className="mb-8 overflow-hidden"
          style={{
            backgroundColor: Colors.cloud,
            borderWidth: 1,
            borderColor: Colors.fog,
            borderRadius: Radius.card,
          }}
        >
          <View className="p-4 bg-[#F8F8F8] border-b border-[#E2E2E2]">
            <Text
              style={{
                fontSize: 13,
                fontWeight: "600",
                color: Colors.pitchBlack,
                textTransform: "uppercase",
                letterSpacing: 0.8,
              }}
            >
              Subscription details
            </Text>
          </View>

          {detailsRows.map((row, index) => (
            <View
              key={row.label}
              className="flex-row justify-between items-center p-4"
              style={{
                borderBottomWidth: index < detailsRows.length - 1 ? 1 : 0,
                borderBottomColor: Colors.fog,
              }}
            >
              <Text style={{ fontSize: 13, color: Colors.graphite, flex: 1 }}>
                {row.label}
              </Text>
              <Text
                style={{
                  fontSize: 13,
                  fontWeight: "500",
                  color: Colors.pitchBlack,
                  flex: 1.5,
                  textAlign: "right",
                }}
              >
                {row.value}
              </Text>
            </View>
          ))}
        </View>

        {/* Action Buttons */}
        <View className="gap-3">
          <AppButton
            title="Manage subscription →"
            onPress={handleManage}
          />

          <AppButton
            title="Share / View Invoice Receipt"
            variant="secondary"
            onPress={handleShareReceipt}
          />

          {!isCancelled && (
            <AppButton
              title={isPaused ? "Resume subscription" : "Pause subscription"}
              variant="secondary"
              onPress={handleTogglePause}
            />
          )}

          {!isCancelled && (
            <Pressable
              onPress={handleCancel}
              className="items-center py-2 mt-1"
            >
              <Text
                style={{
                  fontSize: 13,
                  fontWeight: "500",
                  color: "#DC2626",
                }}
              >
                Cancel subscription
              </Text>
            </Pressable>
          )}

          <Pressable
            onPress={handleDelete}
            className="items-center py-2"
          >
            <Text
              style={{
                fontSize: 12,
                fontWeight: "500",
                color: Colors.ash,
              }}
            >
              Delete from Chronicle
            </Text>
          </Pressable>
        </View>
      </ScrollView>
    </SafeAreaView>
  );
}
